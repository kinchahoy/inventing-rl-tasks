"""Trusted verifier: static Isar style + line-limit gate, then a clean Isabelle build. Prints one JSON verdict.

Generated by quantum-src/gen.py from verify_template.py; edit the template, not this file. Statements are not
compared here: Check.thy compares each theorem term by term (aconv) against the trusted Canonical.thy.
"""

import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

THEORY = "Shor_General"
ALLOWED_IMPORTS: set[str] = set(['Complex_Main', 'Quantum_Basics'])
TRUSTED: tuple[str, ...] = ('Quantum_Basics.thy', 'Canonical.thy', 'Check.thy', 'ROOT')
MAX_LINES = 700
THEOREMS: list[str] = ['shor_factor', 'shor_peak', 'shor_general_success']
ALLOWED_METHODS: set[str] = set(['meson', 'metis'])
FORBIDDEN = [w for w in [
    "apply", "done", "back", "defer", "prefer", "sorry", "oops", "metis", "meson", "smt", "sledgehammer",
    "nitpick", "nunchaku", "quickcheck", "axiomatization", "axioms", "oracle", "ML", "ML_file",
    "ML_val", "ML_command", "ML_prf", "setup", "local_setup", "method_setup", "attribute_setup",
    "simproc_setup", "declaration", "syntax_declaration", "skip_proofs", "quick_and_dirty",
    "ML_export", "ML_file_debug", "ML_file_no_debug", "SML_file", "SML_file_debug",
    "SML_file_no_debug", "SML_export", "SML_import", "tactic", "raw_tactic",
    "parse_translation", "print_translation", "parse_ast_translation", "print_ast_translation",
    "typed_print_translation", "translations", "syntax", "no_syntax",
] if w not in ALLOWED_METHODS]
ISAR_STEP = re.compile(r"\b(have|show|thus|hence|obtain)\b")
TESTS = Path(__file__).parent


def scrub(text: str) -> tuple[str, str]:
    """Drop (nested) comments and (nested) cartouches, which hold prose, text blocks and quoted terms.

    Returns (code, tokens): `code` keeps string literals (for the theory header), `tokens` blanks them too,
    so a forbidden word inside prose or a quoted term is not mistaken for a command or method.
    """
    text = text.replace("‹", "\\<open>").replace("›", "\\<close>")
    code: list[str] = []
    tokens: list[str] = []
    i, n = 0, len(text)
    while i < n:
        if text.startswith("(*", i) or text.startswith("\\<open>", i):
            opener, closer = ("(*", "*)") if text.startswith("(*", i) else ("\\<open>", "\\<close>")
            depth = 0
            while i < n:
                if text.startswith(opener, i):
                    depth, i = depth + 1, i + len(opener)
                elif text.startswith(closer, i):
                    depth, i = depth - 1, i + len(closer)
                    if depth == 0:
                        break
                else:
                    i += 1
            code.append(" ")
            tokens.append(" ")
        elif text[i] in "\"`":
            quote, j = text[i], i + 1
            while j < n and text[j] != quote:
                j += 2 if text[j] == "\\" else 1
            code.append(text[i:j + 1])
            tokens.append(" ")
            i = j + 1
        else:
            code.append(text[i])
            tokens.append(text[i])
            i += 1
    return "".join(code), "".join(tokens)


def style_checks(source: str) -> dict[str, bool | str]:
    code, tokens = scrub(source)
    header = re.search(rf"\btheory\s+{THEORY}\s+imports\s+(.*?)\s+begin\b", code, flags=re.S)
    imports = set() if header is None else {t.strip('"') for t in header.group(1).split()}
    found = sorted({w for w in FORBIDDEN if re.search(rf"(?<![\w.']){w}(?![\w'])", tokens)})
    starts = {
        name: re.search(rf"\btheorem\s*(?:\(\s*in\s+\w+\s*\)\s*)?{name}\b", tokens) for name in THEOREMS
    }
    missing = [name for name, m in starts.items() if m is None]
    first = min((m.start() for m in starts.values() if m is not None), default=-1)
    proofs = tokens[first:] if first >= 0 else ""
    n_lines = len(source.splitlines())
    return {
        "theory_header": header is not None,
        "imports_allowed": header is not None and imports <= ALLOWED_IMPORTS,
        "imports": " ".join(sorted(imports)),
        "no_forbidden_tokens": not found,
        "forbidden_found": " ".join(found),
        "theorems_present": not missing,
        "theorems_missing": " ".join(missing),
        "line_count": str(n_lines),
        "within_line_limit": n_lines <= MAX_LINES,
        "structured_isar_proof": len(ISAR_STEP.findall(proofs)) >= 4 and re.search(r"\bqed\b", proofs) is not None,
    }


def isabelle_build(submission: Path) -> tuple[bool, str]:
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        shutil.copy(submission, work / f"{THEORY}.thy")
        for trusted in TRUSTED:
            shutil.copy(TESTS / trusted, work / trusted)
        try:
            proc = subprocess.run(
                ["isabelle", "build", "-o", "threads=2", "-c", "-D", str(work)],
                capture_output=True, text=True, timeout=540,
            )
        except subprocess.TimeoutExpired:
            return False, "isabelle build timed out"
        log = (proc.stdout + proc.stderr)[-6000:]
        return proc.returncode == 0, log


def main() -> None:
    submission = Path(sys.argv[1]) / f"{THEORY}.thy"
    if not submission.is_file():
        print(json.dumps({"reward": 0.0, "error": f"missing {submission}"}))
        return
    checks: dict[str, bool | str] = style_checks(submission.read_text(encoding="utf-8"))
    gates = [k for k, v in checks.items() if isinstance(v, bool)]
    built, log = isabelle_build(submission)
    checks["isabelle_build_and_check"] = built
    checks["build_log"] = log
    passed = all(checks[k] for k in gates) and built
    print(json.dumps({"reward": 1.0 if passed else 0.0, "checks": checks}, indent=2))


if __name__ == "__main__":
    main()
